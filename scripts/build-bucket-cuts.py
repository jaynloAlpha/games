"""Generate alpha-aware Voronoi puzzle cuts and seam-free silhouettes. Authoring dependencies: Pillow, NumPy."""
from pathlib import Path
import json,re
import numpy as np
from PIL import Image
root=Path(__file__).resolve().parents[1]/'games'/'bucket-captain'; assets=root/'assets'
files=['rocket','monster','park','zebra','giraffe','ultraman','bear','koala','cake','panda','white-tiger','lion','elephant','rhino','hippo','kangaroo','ostrich','golden-monkey','chimpanzee']
def clip(poly,n,limit):
 out=[]
 for a,b in zip(poly,poly[1:]+poly[:1]):
  da=np.dot(a,n)-limit;db=np.dot(b,n)-limit
  if da<=1e-9:out.append(a)
  if (da<0)!=(db<0):out.append((np.array(a)+(np.array(b)-a)*da/(da-db)).tolist())
 return out
allcuts={}
for idx,name in enumerate(files):
 im=Image.open(assets/f'puzzle-{name}.png').convert('RGBA').resize((120,120)); y,x=np.where(np.array(im)[:,:,3]>100);pts=np.column_stack(((x+.5)/120,(y+.5)/120))[::2]; layouts={}
 for count in (4,5,6,8):
  rng=np.random.default_rng(idx*101+count);centers=[pts[rng.integers(len(pts))]]
  for j in range(1,count):
   d=np.min(np.sum((pts[:,None]-np.array(centers))**2,axis=2),axis=1);centers.append(pts[rng.choice(len(pts),p=d/d.sum())])
  centers=np.array(centers)
  for _ in range(65):
   labels=np.argmin(np.sum((pts[:,None]-centers)**2,axis=2),axis=1)
   centers=np.array([pts[labels==j].mean(axis=0) for j in range(count)])
  polygons=[];anchors=[];scales=[]
  for j,c in enumerate(centers):
   poly=[[0,0],[1,0],[1,1],[0,1]]
   for k,other in enumerate(centers):
    if k!=j:poly=clip(poly,2*(other-c),np.dot(other,other)-np.dot(c,c))
   visible=pts[labels==j];anchor=visible[np.argmin(np.sum((visible-c)**2,axis=1))];polygons.append([[round(v,5) for v in p] for p in poly]);anchors.append(anchor.round(5).tolist());scales.append(round(.44/np.max(np.abs(visible-anchor)),4))
  layouts[str(count)]={'centers':anchors,'polygons':polygons,'scales':scales}
 layouts['silhouette']=re.search(r'<path d="([^"]+)"', (assets/f'outline-{name}.svg').read_text(encoding='utf-8')).group(1)
 allcuts[name]=layouts
 svg=(assets/f'outline-{name}.svg').read_text(encoding='utf-8');svg=re.sub(r'<g\b.*?</g>','',svg);(assets/f'silhouette-{name}.svg').write_text(svg,encoding='utf-8')
root.joinpath('puzzle-cuts.js').write_text('/* Alpha-aware irregular cuts, generated by scripts/build-bucket-cuts.py. */\nwindow.BucketPuzzleCuts='+json.dumps(allcuts,separators=(',',':'))+';\n',encoding='utf-8')
print('Generated 19 silhouettes and 4/5/6/8-piece layouts')
